export function aiAdminText(
  key: string,
  language: AIAdminLanguage,
  variables: Record<string, string | number> = {},
): string {
  const template = AI_ADMIN_TRANSLATIONS[key]?.[language] || AI_ADMIN_TRANSLATIONS[key]?.en || key;
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.split(`{{${name}}}`).join(String(replacement)),
    template,
  );
}
